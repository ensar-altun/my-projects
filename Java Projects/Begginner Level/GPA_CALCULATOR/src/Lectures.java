public class Lectures {
    private String name;
    private int weight;
    private double grade;

    public Lectures(String name, int weight,double grade) {
        this.name = name;
        this.weight = weight;
        this.grade = grade;
    }

    public String getName() {
        return name;
    }

    public int getWeight() {
        return weight;
    }
    public double getGrade() {
        return grade;
    }
}

